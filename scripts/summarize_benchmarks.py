#!/usr/bin/env python3
"""Create a Markdown benchmark report from results.json."""

from __future__ import annotations

import argparse
import json
from pathlib import Path
from statistics import mean
from typing import Any


def avg(values: list[float]) -> str:
    return f"{mean(values):.2f}" if values else "n/a"


def value_or_na(value: Any) -> str:
    return "n/a" if value is None else str(value)


def parse_args() -> argparse.Namespace:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("results", help="Path to benchmark results.json")
    return parser.parse_args()


def main() -> int:
    args = parse_args()
    results_path = Path(args.results)
    payload = json.loads(results_path.read_text(encoding="utf-8"))
    out_dir = results_path.parent
    summary = payload.get("summary", {})
    machine = payload.get("machine", {})
    tools = machine.get("tools", {})
    results = payload.get("results", [])

    line_reductions = [float(row["line_reduction_pct"]) for row in results if isinstance(row.get("line_reduction_pct"), (int, float))]
    byte_reductions = [float(row["byte_reduction_pct"]) for row in results if isinstance(row.get("byte_reduction_pct"), (int, float))]
    runtimes = [float(row["duration_seconds"]) for row in results if isinstance(row.get("duration_seconds"), (int, float))]

    lines = [
        "# Benchmark Report",
        "",
        "Generated by `scripts/benchmark.py`, `scripts/plot_benchmarks.py`, and `scripts/summarize_benchmarks.py`.",
        "",
        "## Summary",
        "",
        f"- Total fixtures: {summary.get('total', len(results))}",
        f"- Passed: {summary.get('passed', 0)}",
        f"- Failed: {summary.get('failed', 0)}",
        f"- Average line reduction: {avg(line_reductions)}%",
        f"- Average byte reduction: {avg(byte_reductions)}%",
        f"- Average runtime: {avg(runtimes)} seconds",
        f"- Coverage enabled: {summary.get('coverage_enabled')}",
        f"- Compile/run verification: {summary.get('verify_compile')}",
        "",
        "## Graphs",
        "",
        "![Benchmark status](status.svg)",
        "",
        "![Line reduction](line-reduction.svg)",
        "",
        "![Byte reduction](byte-reduction.svg)",
        "",
        "![Runtime](runtime.svg)",
        "",
        "## Machine",
        "",
        f"- Captured at: {value_or_na(machine.get('captured_at_utc'))}",
        f"- OS: {value_or_na(machine.get('os'))} {value_or_na(machine.get('os_release'))}",
        f"- Kernel: {value_or_na(machine.get('kernel'))}",
        f"- Architecture: {value_or_na(machine.get('architecture'))}",
        f"- CPU: {value_or_na(machine.get('cpu_model'))}",
        f"- Logical CPUs: {value_or_na(machine.get('cpu_count_logical'))}",
        f"- Memory: {value_or_na(machine.get('memory_total'))}",
        "",
        "## Tool Versions",
        "",
    ]

    for tool in ["rustc", "cargo", "clang", "clangd", "gcc", "csmith", "perf"]:
        lines.append(f"- {tool}: {value_or_na(tools.get(tool))}")

    lines.extend(
        [
            "",
            "## Fixtures",
            "",
            "| Case | Status | Runtime (s) | Lines | Line Reduction | Bytes | Byte Reduction | Behavior |",
            "|------|--------|-------------|-------|----------------|-------|----------------|----------|",
        ]
    )

    for row in results:
        lines.append(
            "| {case} | {status} | {runtime} | {input_lines} -> {output_lines} | {line_reduction}% | {input_bytes} -> {output_bytes} | {byte_reduction}% | {behavior} |".format(
                case=row.get("case"),
                status=row.get("status"),
                runtime=row.get("duration_seconds"),
                input_lines=row.get("input_lines"),
                output_lines=value_or_na(row.get("output_lines")),
                line_reduction=value_or_na(row.get("line_reduction_pct")),
                input_bytes=row.get("input_bytes"),
                output_bytes=value_or_na(row.get("output_bytes")),
                byte_reduction=value_or_na(row.get("byte_reduction_pct")),
                behavior=value_or_na(row.get("behavior_preserved")),
            )
        )

    lines.append("")
    (out_dir / "report.md").write_text("\n".join(lines), encoding="utf-8")
    print(f"Wrote benchmark report to {out_dir / 'report.md'}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
